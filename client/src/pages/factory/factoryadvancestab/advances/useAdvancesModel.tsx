function useAdvancesModelPart3({
  formatDisplayDate,
}: Pick<Awaited<ReturnType<typeof useAdvancesModelPart1>>, "formatDisplayDate">) {
  const formatDate = (val: string | null | undefined) => {
    if (!val) return "\u2014";
    try {
      return formatDisplayDate(val);
    } catch {
      return "\u2014";
    }
  };
  return { formatDate };
}
