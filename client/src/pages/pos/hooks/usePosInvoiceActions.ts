import { useReactToPrint } from "react-to-print";
import type { InvoiceSale } from "../pos-components/InvoiceTemplate";
import { columnsFromOperationalRows, exportOperationalWorkbook } from "@/lib/operationalExcelExport";
import type { SaleRow, APIInventoryItem, Location } from "../pos-components/posTypes";

interface PosInvoiceActionsParams {
  rows: SaleRow[];
  savedSale: InvoiceSale | null | undefined;
  stockPrintRef: React.RefObject<HTMLDivElement | null>;
  activeLocation: Location | null;
  apiInventory: APIInventoryItem[];
  toast: (opts: { title: string; description?: string; variant?: "destructive" | "default" }) => void;
  /** Derived from the current authenticated user; no cost values in restricted exports. */
  canSeeFinancials: boolean;
}

/**
 * Print + spreadsheet-export actions (invoice print, stock print, inventory
 * export, sale summary/detailed export).
 * Extracted from usePosHandlers.ts (Phase 18 structural split) — logic unchanged.
 */
export function usePosInvoiceActions({
  rows,
  savedSale,
  stockPrintRef,
  activeLocation,
  apiInventory,
  toast,
  canSeeFinancials,
}: PosInvoiceActionsParams) {
  // The WhatsApp receipt and direct PDF download are generated by the same server
  // invoice renderer. Never print the legacy browser-only InvoiceTemplate here.
  const handlePrint = () => {
    const voucherId = savedSale?.voucher?.id;
    if (!voucherId) {
      toast({ title: "Invoice not ready", description: "Save the sale before printing.", variant: "destructive" });
      return;
    }
    // Open synchronously in the click handler to avoid popup blockers. The
    // browser PDF viewer supplies the Print button and prints identical artwork.
    const pdfUrl = `/api/pos/invoice/${encodeURIComponent(String(voucherId))}/pdf`;
    const printWindow = window.open(pdfUrl, "_blank", "noopener,noreferrer");
    if (!printWindow) {
      toast({
        title: "Pop-up blocked",
        description: "Allow pop-ups to open the invoice PDF and print it.",
        variant: "destructive",
      });
    }
  };

  // ISSUE 6: Real stock print handler
  const handleStockPrint = useReactToPrint({
    contentRef: stockPrintRef,
    documentTitle: `STK_${(activeLocation?.name || "Location").replace(/\s+/g, "_")}_${new Date().toLocaleDateString("en-CA")}`,
  });

  // ISSUE 8: Export inventory as Excel
  const handleExportInventory = async () => {
    if (!activeLocation) {
      toast({ title: "No location", description: "Select a location first.", variant: "destructive" });
      return;
    }
    try {
      const data = (Array.isArray(apiInventory) ? apiInventory : []).map((item) => ({
        Code: item.stockItemCode || "",
        "Item Name": item.stockItemName || "",
        UOM: item.stockItemUom || "",
        "Stock Qty": Number(item.quantity || 0),
        ...(canSeeFinancials
          ? {
              "Avg Rate (USD)": Number(item.averageRate || 0),
              "Total Value (USD)": Number(item.totalValue || 0),
            }
          : {}),
        Group: item.stockGroupName || "",
      }));
      const headers = [
        "Code",
        "Item Name",
        "UOM",
        "Stock Qty",
        ...(canSeeFinancials ? ["Avg Rate (USD)", "Total Value (USD)"] : []),
        "Group",
      ];
      const fileName =
        "Inventory_" +
        activeLocation.name.replace(/\s+/g, "_") +
        "_" +
        new Date().toLocaleDateString("en-CA") +
        ".xlsx";
      await exportOperationalWorkbook({
        title: "POS Inventory",
        fileName,
        filters: [{ label: "Location", value: activeLocation.name }],
        sheets: [
          {
            name: "Inventory",
            columns: columnsFromOperationalRows(data, {
              orderedHeaders: headers,
              types: {
                "Stock Qty": "decimal",
                ...(canSeeFinancials
                  ? {
                      "Avg Rate (USD)": "money" as const,
                      "Total Value (USD)": "money" as const,
                    }
                  : {}),
              },
            }),
            rows: data,
          },
        ],
      });
      toast({ title: "Export successful", description: "Downloaded " + fileName });
    } catch {
      toast({ title: "Export failed", description: "Could not export inventory", variant: "destructive" });
    }
  };

  const handleSummaryExport = async () => {
    const validRows = rows.filter((r) => r.stockItemId && r.quantity > 0);
    if (validRows.length === 0) {
      toast({ title: "Nothing to export", description: "Add items first.", variant: "destructive" });
      return;
    }
    const data = validRows.map((r, i) => ({
      "#": i + 1,
      Item: r.itemName,
      Qty: r.quantity,
      Rate: r.rate,
      Amount: r.amount,
    }));
    try {
      await exportOperationalWorkbook({
        title: "POS Sale Summary",
        fileName: "POS_Summary_" + new Date().toLocaleDateString("en-CA") + ".xlsx",
        sheets: [
          {
            name: "Summary",
            columns: columnsFromOperationalRows(data, {
              orderedHeaders: ["#", "Item", "Qty", "Rate", "Amount"],
              types: { "#": "integer", Qty: "decimal", Rate: "money", Amount: "money" },
            }),
            rows: data,
          },
        ],
      });
      toast({ title: "Summary exported" });
    } catch {
      toast({ title: "Export failed", description: "Could not export POS summary", variant: "destructive" });
    }
  };

  const handleDetailedExport = async () => {
    const validRows = rows.filter((r) => r.stockItemId && r.quantity > 0);
    if (validRows.length === 0) {
      toast({ title: "Nothing to export", description: "Add items first.", variant: "destructive" });
      return;
    }
    const data = validRows.map((r, i) => {
      const cfgUSD = r.configuredPrice ?? 0;
      const plBale = r.rateUSD - cfgUSD;
      return {
        "#": i + 1,
        Code: r.stockItemCode || "",
        Item: r.itemName,
        Qty: r.quantity,
        "Rate (USD)": r.rateUSD,
        Amount: r.amount,
        ...(canSeeFinancials
          ? {
              "P/L per unit": cfgUSD > 0 ? plBale : null,
              "Total P/L": cfgUSD > 0 ? plBale * r.quantity : null,
            }
          : {}),
      };
    });
    try {
      await exportOperationalWorkbook({
        title: "POS Sale Details",
        fileName: "POS_Detailed_" + new Date().toLocaleDateString("en-CA") + ".xlsx",
        sheets: [
          {
            name: "Detailed",
            columns: columnsFromOperationalRows(data, {
              orderedHeaders: [
                "#",
                "Code",
                "Item",
                "Qty",
                "Rate (USD)",
                "Amount",
                ...(canSeeFinancials ? ["P/L per unit", "Total P/L"] : []),
              ],
              types: {
                "#": "integer",
                Qty: "decimal",
                "Rate (USD)": "money",
                Amount: "money",
                ...(canSeeFinancials ? { "P/L per unit": "money" as const, "Total P/L": "money" as const } : {}),
              },
            }),
            rows: data,
          },
        ],
      });
      toast({ title: "Detailed export downloaded" });
    } catch {
      toast({ title: "Export failed", description: "Could not export POS details", variant: "destructive" });
    }
  };

  return { handlePrint, handleStockPrint, handleExportInventory, handleSummaryExport, handleDetailedExport };
}
